#!/usr/bin/env bash
# Native-stack environment for Flip the Switch.
# Secrets are read from the stack .env generated earlier (never printed here).
set -a
ENVF="$HOME/workspace/flip-the-switch/stack/.env"
_val() { grep "^$1=" "$ENVF" | head -1 | cut -d= -f2-; }

DB_HOST=127.0.0.1
DB_PORT=5432
DB_USER=$(_val DB_USER)
DB_PASSWORD=$(_val DB_PASSWORD)
DB_OWNER_USER=$(_val DB_OWNER_USER)
DB_OWNER_PASSWORD=$(_val DB_OWNER_PASSWORD)
DB_NAME=$(_val DB_NAME)
ID_SERVER_NAME=localhost
MATRIX_SERVER_NAME=localhost
AGENT_REGISTRATION_TOKEN=$(_val AGENT_REGISTRATION_TOKEN)
SECRET_KEYS=$(_val SECRET_KEYS)
JWT_SECRET_KEY=$(_val JWT_SECRET_KEY)
CONTROLLER_TOKEN_SECRET=$(_val CONTROLLER_TOKEN_SECRET)
GATEWAY_COOKIE_SECURE=false
GATEWAY_ADMIN_EMAIL=$(_val GATEWAY_ADMIN_EMAIL)
GATEWAY_ADMIN_PASSWORD=$(_val GATEWAY_ADMIN_PASSWORD)
FRONTEND_BASE_URL=http://localhost:8000
OUTBOUND_ALLOWED_PRIVATE_HOSTS=127.0.0.1,localhost
TELEMETRY_ENABLED=false
GATEWAY_UI_DIR=$HOME/workspace/flip-the-switch/runtime/gateway-ui

MATTERMOST_ADMIN_USER=$(_val MATTERMOST_ADMIN_USER)
MATTERMOST_ADMIN_PASSWORD=$(_val MATTERMOST_ADMIN_PASSWORD)
MATTERMOST_TEAM_NAME=$(_val MATTERMOST_TEAM_NAME)
MATTERMOST_USER=$(_val MATTERMOST_USER)
MATTERMOST_USER_PASSWORD=$(_val MATTERMOST_USER_PASSWORD)
set +a
